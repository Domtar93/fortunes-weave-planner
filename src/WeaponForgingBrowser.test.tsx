import { openPlannerPanel, plannerRole , withinPlanner } from './plannerTestUtils'
import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'
import { createPreset, PRESET_KEY } from './presets'
import { STATS } from './growths'

const browser = () => plannerRole('region', { name: 'Weapon and forging reference browser' })
const catalog = () => withinPlanner(browser()).getByRole('list', { name: 'Main weapon catalog' })
const detail = (name: string) => withinPlanner(browser()).getByRole('region', { name: `${name} weapon details` })
const stats = (name: string) => Object.fromEntries([...detail(name).querySelectorAll('.weapon-stats > div')].map(div => [div.querySelector('dt')?.textContent, div.querySelector('dd')?.textContent]))
async function open() {
  const user = userEvent.setup()
  render(<App />)
  await openPlannerPanel(user, 'Weapons & Forging')
  await screen.findByRole('region', { name: 'Weapon and forging reference browser' })
  return user
}
async function inspect(user: ReturnType<typeof userEvent.setup>, name: string) { await user.click(withinPlanner(catalog()).getByRole('button', { name: `Inspect weapon ${name}` })) }
afterEach(() => { cleanup(); localStorage.clear() })

describe('Weapons & Forging browser', () => {
  it('starts collapsed and renders all 91 main records without adding preliminary weapons', async () => {
    render(<App />)
    expect(screen.getByText('Weapons & Forging').closest('details')?.open).toBe(false)
    expect(screen.queryByRole('list', { name: 'Main weapon catalog' })).toBeNull()
    await openPlannerPanel(userEvent, 'Weapons & Forging')
    await screen.findByRole('list', { name: 'Main weapon catalog' })
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(91)
    expect(withinPlanner(catalog()).queryByRole('button', { name: 'Inspect weapon Veronique' })).toBeNull()
    expect(withinPlanner(browser()).getByText('Preliminary evidence · five separate contributions')).toBeDefined()
  })
  it('shows Wooden Sword values, original wording, preliminary evidence and exact source links', async () => {
    const user = await open()
    expect(stats('Wooden Sword')).toEqual({ Hit: '90', 'Documented Might': '2-20', 'Attack range': '1', Weight: '2', Critical: '0', Durability: '10', 'Maximum refinement': '9' })
    const comparison = withinPlanner(detail('Wooden Sword')).getByLabelText('Preliminary comparison Wooden Sword')
    expect(comparison.textContent).toContain('Grants Spd+5')
    expect(comparison.textContent).toContain('wording')
    const table = withinPlanner(comparison).getByRole('table')
    expect(table.textContent).toContain('Main · row 19')
    expect(table.textContent).toContain('Preliminary · row 2')
    expect(table.querySelectorAll('tbody td')[0].textContent).not.toBe(table.querySelectorAll('tbody td')[1].textContent)
    const source = withinPlanner(detail('Wooden Sword')).getAllByRole('link', { name: 'Forging!A19:J19' })[0] as HTMLAnchorElement
    expect(new URL(source.href).searchParams.get('sheet')).toBe('Forging')
    expect(new URL(source.href).searchParams.get('range')).toBe('A19:J19')
    await user.click(withinPlanner(detail('Wooden Sword')).getByText('Raw source cells · Wooden Sword · row 2', { exact: true }))
    expect(withinPlanner(detail('Wooden Sword')).getAllByText('=9', { exact: true })).toHaveLength(1)
  })
  it('searches names, effects and combat arts with combined filters', async () => {
    const user = await open()
    await user.type(screen.getByLabelText('Weapon name'), 'levin')
    await user.type(screen.getByLabelText('Special-effect text'), 'magical')
    await user.type(screen.getByLabelText('Combat art / note search'), 'Lightning')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(1)
    await inspect(user, 'Levin Sword')
    expect(stats('Levin Sword')).toMatchObject({ Hit: '70', 'Documented Might': '12-20', 'Attack range': '1-2', Weight: '8', 'Maximum refinement': '3' })
    expect(detail('Levin Sword').textContent).toContain('Treated as a magical attack')
    expect(detail('Levin Sword').textContent).toContain('Lightning Strike')
    expect(detail('Levin Sword').textContent).toContain('Excel d-m display')
    expect(detail('Levin Sword').textContent).toContain('2026-02-01T00:00:00')
    expect(detail('Levin Sword').textContent).toContain('Excel serial 46054')
  })
  it('filters completeness, keeps four incomplete primary records browseable and Silver durability unknown', async () => {
    const user = await open()
    await user.selectOptions(screen.getByLabelText('Record completeness'), 'primary-incomplete')
    expect(withinPlanner(catalog()).getAllByRole('button').map(button => button.getAttribute('aria-label'))).toEqual(['Inspect weapon Whirlwind Blade', 'Inspect weapon Shining Spear', 'Inspect weapon Dodge Gauntlets', 'Inspect weapon Zerberus'])
    for (const name of ['Whirlwind Blade', 'Shining Spear', 'Dodge Gauntlets', 'Zerberus']) {
      await inspect(user, name)
      expect(stats(name).Hit).toBe('Not documented')
      expect(detail(name).textContent).toContain('Primary combat stats missing')
    }
    await user.selectOptions(screen.getByLabelText('Record completeness'), 'incomplete')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(5)
    await inspect(user, 'Silver Spear')
    expect(stats('Silver Spear')).toEqual({ Hit: '85', 'Documented Might': '20-25', 'Attack range': '1', Weight: '6', Critical: '0', Durability: 'Not documented', 'Maximum refinement': '3' })
    const comparison = withinPlanner(detail('Silver Spear')).getByRole('table')
    expect(comparison.textContent).toContain('Not documented')
    expect(comparison.textContent).toContain('20')
    await user.selectOptions(screen.getByLabelText('Record completeness'), 'complete')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(86)
    expect(detail('Silver Spear').textContent).toContain('outside the filters')
  })
  it('filters numerical conflicts and shows Zanbato versions without overwriting', async () => {
    const user = await open()
    await user.selectOptions(screen.getByLabelText('Source conflicts / differences'), 'numeric')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(1)
    await inspect(user, 'Zanbato')
    expect(stats('Zanbato')).toEqual({ Hit: '80', 'Documented Might': '14-19', 'Attack range': '1', Weight: '7', Critical: '0', Durability: '20', 'Maximum refinement': '3' })
    const comparison = withinPlanner(detail('Zanbato')).getByRole('table')
    expect(comparison.textContent).toContain('7-19')
    expect(comparison.textContent).toContain('14-19')
    expect(comparison.textContent).toContain('numeric')
    expect(withinPlanner(detail('Zanbato')).getByRole('link', { name: 'Forging!A4:J4' })).toBeDefined()
    expect(withinPlanner(detail('Zanbato')).getAllByRole('link', { name: 'Forging!A25:J25' })[0]).toBeDefined()
  })
  it('shows the unmerged possible spelling variant and Da Mina wording evidence', async () => {
    const user = await open()
    await user.selectOptions(screen.getByLabelText('Source conflicts / differences'), 'possible-spelling')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(1)
    await inspect(user, 'Veroquine')
    const comparison = withinPlanner(detail('Veroquine')).getByLabelText('Preliminary comparison Veronique')
    expect(comparison.textContent).toContain('manual confirmation required')
    expect(comparison.textContent).toContain('remain separate, not merged')
    expect(comparison.textContent).toContain('Forging!A6:J6')
    await user.selectOptions(screen.getByLabelText('Source conflicts / differences'), 'any')
    expect(withinPlanner(catalog()).getAllByRole('button')).toHaveLength(5)
    await inspect(user, 'Da Mina Gauntlets')
    expect(withinPlanner(detail('Da Mina Gauntlets')).getByRole('table').textContent).toContain('Hit/Crit +10')
    expect(withinPlanner(detail('Da Mina Gauntlets')).getByRole('table').textContent).toContain('Hit/Crit+10')
  })
  it('shows single Might, valid zero refinement and absent effects without a slider or equipment controls', async () => {
    const user = await open()
    await inspect(user, "Ursa's Right Claw")
    expect(stats("Ursa's Right Claw")['Documented Might']).toBe('15')
    expect(stats("Ursa's Right Claw")['Maximum refinement']).toBe('0')
    expect(detail("Ursa's Right Claw").textContent).toContain('Single documented Might: 15')
    expect(detail("Ursa's Right Claw").textContent).toContain('Violent Claw')
    expect(detail("Ursa's Right Claw").textContent).toContain('Cursed +1')
    expect(withinPlanner(browser()).queryByRole('slider')).toBeNull()
    expect(withinPlanner(browser()).queryByRole('button', { name: /equip/i })).toBeNull()
    expect(withinPlanner(browser()).queryByLabelText(/weapon type/i)).toBeNull()
  })
  it('keeps independent research notes separate from weapon details and preserves all five preliminary contributions', async () => {
    const user = await open()
    await user.click(withinPlanner(browser()).getByText('Independent forging research notes · unverified'))
    const notes = withinPlanner(browser()).getByText('Independent forging research notes · unverified').closest('details')!
    expect(notes.textContent).toContain('Most effects unlock halfway or at full refine')
    expect(notes.textContent).toContain('Forging!K18')
    expect(detail('Wooden Sword').textContent).not.toContain('Most effects unlock halfway')
    await user.click(withinPlanner(browser()).getByText('Preliminary evidence · five separate contributions'))
    const prelim = withinPlanner(browser()).getByText('Preliminary evidence · five separate contributions').closest('details')!
    expect(withinPlanner(prelim).getAllByRole('heading', { level: 3 })).toHaveLength(5)
    expect(prelim.textContent).toContain('Veronique · row 6')
  })
  it('retains selection and queries across collapse and planner changes without altering growths or comparisons', async () => {
    const user = await open()
    const before = STATS.map(stat => screen.getByTestId(`combined-${stat}`).textContent)
    await user.type(screen.getByLabelText('Weapon name'), 'Zanbato')
    await inspect(user, 'Zanbato')
    expect(STATS.map(stat => screen.getByTestId(`combined-${stat}`).textContent)).toEqual(before)
    await openPlannerPanel(user, 'Weapons & Forging')
    await user.selectOptions(plannerRole('combobox', { name: /^Character$/ }), 'Sofia')
    await openPlannerPanel(user, 'Weapons & Forging')
    expect((screen.getByLabelText('Weapon name') as HTMLInputElement).value).toBe('Zanbato')
    expect(detail('Zanbato')).toBeDefined()
    expect(browser().textContent).toContain('Reference for Sofia as Gladiator')
    expect(screen.getByTestId('combined-Mag').textContent).toBe('45%')
    expect((screen.getByLabelText('Build A character') as HTMLSelectElement).value).toBe('Alexandra')
    expect((screen.getByLabelText('Build B class') as HTMLSelectElement).value).toBe('Hunter')
  })
  it('loads an existing version-one saved build while weapon filters and storage remain unchanged', async () => {
    const preset = createPreset('Existing Sofia', { characterName: 'Sofia', className: 'Gladiator' }, [])
    const payload = JSON.stringify({ schemaVersion: 1, presets: [preset] })
    localStorage.setItem(PRESET_KEY, payload)
    const user = await open()
    await inspect(user, 'Levin Sword')
    await openPlannerPanel(user, 'My Character Builds')
    const group = plannerRole('group', { name: 'Load Existing Sofia' })
    await user.click(withinPlanner(group).getByRole('button', { name: 'Load into Main planner' }))
    expect((plannerRole('combobox', { name: /^Character$/ }) as HTMLSelectElement).value).toBe('Sofia')
    expect(detail('Levin Sword')).toBeDefined()
    expect(browser().textContent).toContain('Reference for Sofia as Gladiator')
    expect(screen.getByTestId('combined-Mag').textContent).toBe('45%')
    expect(localStorage.getItem(PRESET_KEY)).toBe(payload)
  })
})



