import imported from './runtimeData'
import { normalizeCatalogText } from './dungeons'

export type FieldState = 'documented' | 'literal-formula' | 'source-display' | 'missing' | 'unresolved'
export interface RawWeaponField { raw: string | number | boolean | null; rawType: string; source: string; numberFormat: string | null }
export interface WeaponNumber extends RawWeaponField { value: number | null; state: FieldState }
export interface WeaponText extends RawWeaponField { text: string | null; state: FieldState }
export interface WeaponRange extends WeaponText { excelSerial: number | null }
export interface WeaponMight extends RawWeaponField { text: string | null; kind: 'span' | 'single' | 'missing' | 'unresolved'; value: number | null; lower: number | null; upper: number | null }
export type WeaponFieldKey = 'nameSource' | 'hit' | 'might' | 'attackRange' | 'weight' | 'critical' | 'durability' | 'effects' | 'maxRefinement' | 'additionalNote'
export interface WeaponForgingRecord {
  id: string; name: string; section: 'main' | 'preliminary'; source: { sheet: string; row: number; range: string }
  reliability: 'unverified'; completeness: 'complete' | 'incomplete'; primaryCompleteness: 'complete' | 'incomplete'; missingFields: string[]
  validation: { severity: string; code: string; location: string; message: string }[]
  nameSource: WeaponText; hit: WeaponNumber; might: WeaponMight; attackRange: WeaponRange; weight: WeaponNumber
  critical: WeaponNumber; durability: WeaponNumber; effects: WeaponText; maxRefinement: WeaponNumber; additionalNote: WeaponText
}
export interface WeaponRelationship {
  mainId: string; preliminaryId: string; match: 'exact-name' | 'possible-spelling'
  differences: { field: WeaponFieldKey; kind: 'wording' | 'missing-data' | 'numeric'; mainSource: string; preliminarySource: string }[]
}
// JSON is generated by the validating importer. Narrow enumerations explicitly at this boundary.
function record(value: (typeof imported.forging.records)[number] | (typeof imported.forging.preliminary)[number]): WeaponForgingRecord {
  if (!['main', 'preliminary'].includes(value.section) || value.reliability !== 'unverified'
    || !['complete', 'incomplete'].includes(value.completeness) || !['complete', 'incomplete'].includes(value.primaryCompleteness)) throw new Error('Invalid weapon metadata')
  for (const key of Object.keys(WEAPON_FIELDS) as WeaponFieldKey[]) {
    const field = value[key]
    if ('state' in field && !['documented', 'literal-formula', 'source-display', 'missing', 'unresolved'].includes(field.state)) throw new Error(`Invalid weapon field: ${key}`)
    if ('kind' in field && !['span', 'single', 'missing', 'unresolved'].includes(field.kind)) throw new Error('Invalid Might representation')
  }
  return value as WeaponForgingRecord
}
export const WEAPON_FIELDS: Record<WeaponFieldKey, string> = { nameSource: 'Name', hit: 'Hit', might: 'Documented Might', attackRange: 'Attack range', weight: 'Weight', critical: 'Critical', durability: 'Durability', effects: 'Special effects', maxRefinement: 'Maximum refinement', additionalNote: 'Combat art / additional note' }
export const weaponData = {
  records: imported.forging.records.map(record), preliminary: imported.forging.preliminary.map(record),
  relationships: imported.forging.relationships as WeaponRelationship[], generalNotes: imported.forging.generalNotes,
}
export function weaponFieldText(weapon: WeaponForgingRecord, key: WeaponFieldKey): string {
  const field = weapon[key]
  if (('kind' in field && ['missing', 'unresolved'].includes(field.kind)) || ('state' in field && ['missing', 'unresolved'].includes(field.state))) return 'Not documented'
  return ('value' in field && key !== 'might' ? field.value?.toString() : 'text' in field ? field.text : null) ?? 'Not documented'
}
export type CompletenessFilter = 'all' | 'complete' | 'incomplete' | 'primary-incomplete'
export type ConflictFilter = 'all' | 'any' | 'numeric' | 'wording' | 'missing-data' | 'possible-spelling'
export function filterWeapons(options: { name: string; effect: string; combatArt: string; completeness: CompletenessFilter; conflict: ConflictFilter }, records = weaponData.records): WeaponForgingRecord[] {
  const queries = [options.name, options.effect, options.combatArt].map(normalizeCatalogText)
  return records.filter(weapon => {
    const values = [weapon.name, weapon.effects.text ?? '', weapon.additionalNote.text ?? ''].map(normalizeCatalogText)
    const related = weaponData.relationships.filter(entry => entry.mainId === weapon.id)
    return queries.every((query, index) => !query || values[index].includes(query))
      && (options.completeness === 'all' || (options.completeness === 'primary-incomplete' ? weapon.primaryCompleteness === 'incomplete' : weapon.completeness === options.completeness))
      && (options.conflict === 'all' || related.some(entry => options.conflict === 'any' || entry.match === options.conflict || entry.differences.some(diff => diff.kind === options.conflict)))
  })
}


