import { defineConfig } from 'vitest/config'
import type { Plugin } from 'vite'
import react from '@vitejs/plugin-react'

// Offline support (November 22, 2026). At build time, emit sw.js with the exact list of
// built scripts, styles and the page, so the planner works offline after one visit.
// Hashed files never change, so they are served from the cache; the page itself is
// fetched fresh when online so new releases show up straight away.
const SHELL = ['./', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png']
const serviceWorkerSource = (version: string, files: string[]) => `// Generated by vite.config.ts. Do not edit.
const CACHE = 'fw-planner-${version}'
const PRECACHE = ${JSON.stringify(files)}
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(PRECACHE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith('fw-planner-') && key !== CACHE).map(key => caches.delete(key))))
    .then(() => self.clients.claim()))
})
self.addEventListener('fetch', event => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then(response => {
      const copy = response.clone(); caches.open(CACHE).then(cache => cache.put('./', copy)); return response
    }).catch(() => caches.match('./')))
    return
  }
  event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(response => {
    if (response.ok) { const copy = response.clone(); caches.open(CACHE).then(cache => cache.put(request, copy)) }
    return response
  })))
})
`
function offlineServiceWorker(): Plugin {
  return {
    name: 'planner-offline-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      // The individual community research sheets (sheet-*.js) are cached when first opened
      // rather than up front, which keeps the first download small.
      const built = Object.keys(bundle).filter(file => /\.(?:js|css)$/u.test(file) && !/(?:^|\/)sheet-[^/]*\.js$/u.test(file)).sort()
      const files = [...SHELL, ...built]
      let hash = 5381
      for (const char of files.join('\n')) hash = (hash * 33 + char.charCodeAt(0)) >>> 0
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource(hash.toString(36), files) })
    },
  }
}

export default defineConfig({
  // Relative URLs so the same build works at any address, including a GitHub Pages
  // project page such as https://<user>.github.io/<repository>/.
  base: './',
  plugins: [react(), offlineServiceWorker()],
  build: {
    rollupOptions: {
      output: {
        // Independently cache immutable reference data; keep synchronous model imports.
        manualChunks(id) {
          if(id.replace(/\\/gu,'/').endsWith('/src/data/character-bases.json'))return 'data-character-bases'
          if(/\/src\/data\/(?:personal-ability-research|ability-research)\.json$/u.test(id.replace(/\\/gu,'/')))return 'data-ability-research'
          if(id.replace(/\\/gu,'/').endsWith('/src/data/ability-info-runtime.json'))return 'data-ability-info'
          if(id.replace(/\\/gu,'/').endsWith('/src/data/community-runtime.json'))return 'data-community'
          const match = id.replace(/\\/gu, '/').match(/\/src\/data\/runtime\/(reference|proficiencies-[123])\.json$/u)
          return match ? `data-${match[1]}` : undefined
        },
      },
    },
  },
  // Source-rich UI workflows exercise up to 69 selections on slower local/CI hosts.
  test: { environment: 'jsdom', include: ['src/**/*.test.{ts,tsx}'], minWorkers: 1, maxWorkers: 2, testTimeout: 15000 },
})
